/* Pure rules for UAE real estate (rent cap, notice deadline, advertising permit, KYC). No server needed:  npx tsx tests/uae-rules.ts */
import { ok, sec, finish } from './_api'
import { SWK_NAV } from '../src/web/swk/nav'
import { ENTITIES } from '../src/shared/entities'
import { RERA_BANDS, reraIncrease, noticeDeadline, renewalCheck, permitStatus, permitUsable, KYC_STANDARD_CHECKS, nextKycReview } from '../src/shared/uae-rules'

sec('RERA rent-increase bands')
ok('five bands', RERA_BANDS.length === 5)
ok('rent at the index allows 0%', reraIncrease(100000, 100000).maxIncreasePct === 0)
ok('rent above the index allows 0%', reraIncrease(120000, 100000).maxIncreasePct === 0)
ok('10% below index allows 0%', reraIncrease(90000, 100000).maxIncreasePct === 0)
ok('15% below index allows 5%', reraIncrease(85000, 100000).maxIncreasePct === 5)
ok('25% below index allows 10%', reraIncrease(75000, 100000).maxIncreasePct === 10)
ok('35% below index allows 15%', reraIncrease(65000, 100000).maxIncreasePct === 15)
ok('50% below index allows 20%', reraIncrease(50000, 100000).maxIncreasePct === 20)
ok('max rent is rent plus the allowed %', Math.round(reraIncrease(75000, 100000).maxRent) === 82500)
ok('no index gives 0% (no division by zero)', reraIncrease(75000, 0).maxIncreasePct === 0)

sec('Notice deadline')
ok('90 days before 2026-12-31 is 2026-10-02', noticeDeadline('2026-12-31', 90) === '2026-10-02', noticeDeadline('2026-12-31', 90))
ok('60 days notice', noticeDeadline('2026-12-31', 60) === '2026-11-01', noticeDeadline('2026-12-31', 60))
ok('empty date gives null', noticeDeadline('', 90) === null)
ok('datetime string accepted', noticeDeadline('2026-12-31T00:00:00', 90) === '2026-10-02')

sec('Renewal check')
const base = { currentRent: 75000, endDate: '2026-12-31', noticeDays: 90 }
let c = renewalCheck({ ...base, newRent: 75000, indexAverage: 100000 })
ok('same rent: no problems and no notice needed', c.problems.length === 0 && c.increasePct === 0, c)
c = renewalCheck({ ...base, newRent: 70000, indexAverage: 100000 })
ok('lower rent: no problems', c.problems.length === 0)
c = renewalCheck({ ...base, newRent: 82500, indexAverage: 100000, noticeSentOn: '2026-09-01' })
ok('increase at the cap with timely notice passes', c.problems.length === 0 && c.maxRent === 82500 && c.maxIncreasePct === 10, c)
c = renewalCheck({ ...base, newRent: 90000, indexAverage: 100000, noticeSentOn: '2026-09-01' })
ok('increase above the cap is flagged', c.problems.length === 1 && /above the RERA limit of 10%/.test(c.problems[0]), c)
c = renewalCheck({ ...base, newRent: 80000, noticeSentOn: '2026-09-01' })
ok('increase without an index average is flagged', c.problems.some(p => /index average/.test(p)), c)
c = renewalCheck({ ...base, newRent: 80000, indexAverage: 100000 })
ok('increase without a notice is flagged', c.problems.some(p => /No written/.test(p)), c)
c = renewalCheck({ ...base, newRent: 80000, indexAverage: 100000, noticeSentOn: '2026-10-03' })
ok('late notice is flagged', c.problems.some(p => /after the deadline of 2026-10-02/.test(p)), c)
c = renewalCheck({ ...base, newRent: 80000, indexAverage: 100000, noticeSentOn: '2026-10-02' })
ok('notice on the deadline day is on time', c.problems.length === 0, c)
c = renewalCheck({ ...base, newRent: 90000, indexAverage: 100000 })
ok('two problems are both reported', c.problems.length === 2, c)

sec('Advertising permit status')
const today = '2026-10-26'
ok('no number is Missing', permitStatus('', '2027-01-01', today) === 'Missing')
ok('blank spaces is Missing', permitStatus('   ', '2027-01-01', today) === 'Missing')
ok('number without expiry is No expiry', permitStatus('123', '', today) === 'No expiry')
ok('far expiry is Valid', permitStatus('123', '2027-01-01', today) === 'Valid')
ok('expiry within 30 days is Expiring', permitStatus('123', '2026-11-10', today) === 'Expiring')
ok('expiry in 30 days exactly is Expiring', permitStatus('123', '2026-11-25', today) === 'Expiring')
ok('expiry in 31 days is Valid', permitStatus('123', '2026-11-26', today) === 'Valid')
ok('expiry today is still usable', permitStatus('123', today, today) === 'Expiring')
ok('past expiry is Expired', permitStatus('123', '2026-10-25', today) === 'Expired')
ok('custom warning window', permitStatus('123', '2026-12-01', today, 60) === 'Expiring')
ok('Missing and Expired block advertising', !permitUsable('Missing') && !permitUsable('Expired'))
ok('other states allow advertising', (['No expiry', 'Valid', 'Expiring'] as const).every(permitUsable))

sec('KYC')
ok('nine standard checks', KYC_STANDARD_CHECKS.length === 9)
ok('standard checks are unique', new Set(KYC_STANDARD_CHECKS).size === 9)
ok('high risk reviewed in 6 months', nextKycReview('2026-01-15', 'High') === '2026-07-15')
ok('medium risk reviewed in 12 months', nextKycReview('2026-01-15', 'Medium') === '2027-01-15')
ok('low risk reviewed in 24 months', nextKycReview('2026-01-15', 'Low') === '2028-01-15')
ok('unknown risk uses medium', nextKycReview('2026-01-15', '') === '2027-01-15')
ok('no review date gives null', nextKycReview('', 'High') === null)

sec('Menu')
const items = SWK_NAV.flatMap(sec => sec.items)
for (const to of ['/e/dld_filings', '/e/kyc_checks', '/e/aml_reports']) ok(`menu has ${to}`, items.some(i => i.to === to), items.map(i => i.to))
const missing = items.filter(i => i.to.startsWith('/e/')).filter(i => !ENTITIES[i.to.split('/')[2]])
ok('every /e/ menu link points to a real entity', missing.length === 0, missing.map(i => i.to))
const entityModules = items.filter(i => i.to.startsWith('/e/') && ENTITIES[i.to.split('/')[2]]).filter(i => i.module && ENTITIES[i.to.split('/')[2]].module !== i.module && !['mandates', 'transactions', 'sales', 'leases', 'finance', 'hr', 'documents', 'compliance', 'crm', 'properties', 'masters', 'admin'].includes(i.module))
ok('menu modules are known modules', entityModules.length === 0, entityModules.map(i => i.to))
finish()
